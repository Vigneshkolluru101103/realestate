/**
 * Creates and triggers download of a valid PDF file.
 * Handles Blob creation, MIME type application/pdf, and URL cleanup.
 *
 * @param {Object} agreement Agreement metadata
 * @param {Object} options Configuration options
 * @param {boolean} options.isDraft If true, adds draft watermark
 * @param {string} options.filename Custom download filename
 */
export function downloadAgreementPdf(agreement, options = {}) {
  if (!agreement || typeof agreement !== 'object') {
    throw new Error('Agreement record is missing or invalid.');
  }
  if (!agreement.id) {
    throw new Error('Agreement Reference ID is required to generate PDF.');
  }

  const { isDraft = false, filename } = options;
  const pdfBytes = createAgreementPdfBytes(agreement, options);

  const downloadName =
    filename ||
    (isDraft
      ? `ZapDocs_DRAFT_${agreement.id}.pdf`
      : `ZapDocs_Legal_Agreement_${agreement.id}.pdf`);

  downloadPdfBytes(pdfBytes, downloadName);
}

