/**
 * ZapDocs PDF Generation Utility
 * Generates 100% compliant PDF 1.4 binary documents natively in pure JavaScript.
 * Ensures valid file signatures, proper cross-reference tables, stream objects,
 * and prominent 'UNEXECUTED DRAFT' watermark for pending agreements.
 */

// Helper to escape PDF text string literals
function escapePdfText(str) {
  if (!str) return '';
  return String(str)
    .replace(/\\/g, '\\\\')
    .replace(/\(/g, '\\(')
    .replace(/\)/g, '\\)');
}

function normalizePdfText(value) {
  return String(value ?? '')
    .replace(/₹/g, 'Rs. ')
    .replace(/[–—]/g, '-')
    .replace(/[‘’]/g, "'")
    .replace(/[“”]/g, '"')
    .replace(/[^\x20-\x7E]/g, '?');
}

function wrapPdfText(value, maxChars = 88) {
  const text = normalizePdfText(value).trim();
  if (!text) return [''];

  const words = text.split(/\s+/);
  const lines = [];
  let current = '';

  words.forEach((word) => {
    const candidate = current ? `${current} ${word}` : word;
    if (candidate.length <= maxChars) {
      current = candidate;
      return;
    }

    if (current) lines.push(current);
    current = word;
  });

  if (current) lines.push(current);
  return lines;
}

/**
 * Builds a readable, single-page PDF 1.4 document for structured text content.
 * This keeps lightweight document exports consistent with the agreement PDF flow
 * without requiring a browser print dialog or an additional dependency.
 *
 * @param {Object} options
 * @param {string} options.title Document title
 * @param {string} options.subtitle Supporting title text
 * @param {Array<{ text: string, bold?: boolean, spaceBefore?: number }>} options.lines Body lines
 * @param {string} options.subject PDF metadata subject
 * @returns {Uint8Array} Binary PDF data
 */
export function createTextPdfBytes({ title, subtitle = '', lines = [], subject = '' } = {}) {
  if (!title || typeof title !== 'string') {
    throw new Error('A document title is required to generate PDF.');
  }
  if (!Array.isArray(lines)) {
    throw new Error('PDF document lines must be provided as an array.');
  }

  const bodyEntries = lines.flatMap((entry) => {
    const normalizedEntry = typeof entry === 'string' ? { text: entry } : entry || {};
    const wrapped = wrapPdfText(normalizedEntry.text);
    return wrapped.map((text, index) => ({
      text,
      bold: Boolean(normalizedEntry.bold),
      spaceBefore: index === 0 ? Number(normalizedEntry.spaceBefore) || 0 : 0
    }));
  });

  let y = 710;
  const streamLines = [
    'q',
    '0.08 0.24 0.55 rg',
    '36 750 523 56 re',
    'f',
    'Q',
    'q',
    '1 1 1 rg',
    'BT',
    '/F2 16 Tf',
    '50 780 Td',
    `(${escapePdfText(normalizePdfText(title))}) Tj`,
    'ET',
    'BT',
    '/F1 9 Tf',
    '50 763 Td',
    `(${escapePdfText(normalizePdfText(subtitle))}) Tj`,
    'ET',
    'Q'
  ];

  bodyEntries.forEach((entry) => {
    y -= entry.spaceBefore;
    if (y < 54) {
      throw new Error('PDF content exceeds the available page length.');
    }
    streamLines.push(
      'BT',
      entry.bold ? '/F2 9.5 Tf' : '/F1 9 Tf',
      entry.bold ? '0.08 0.24 0.55 rg' : '0.15 0.15 0.15 rg',
      `50 ${y} Td`,
      `(${escapePdfText(entry.text)}) Tj`,
      'ET'
    );
    y -= entry.bold ? 16 : 13;
  });

  streamLines.push(
    'q',
    '0.82 0.86 0.92 RG',
    '0.5 w',
    '36 38 m 559 38 l',
    'S',
    'Q',
    'BT',
    '/F1 7 Tf',
    '0.4 0.4 0.4 rg',
    '36 24 Td',
    `(Generated by ZapDocs LegalTech Platform on ${escapePdfText(new Date().toISOString())}) Tj`,
    'ET'
  );

  const streamContent = streamLines.join('\n');
  const encoder = new TextEncoder();
  const streamLength = encoder.encode(streamContent).length;
  const createdAt = new Date().toISOString().replace(/[-:T]/g, '').slice(0, 14);
  const objects = [
    '1 0 obj\n<< /Type /Catalog /Pages 2 0 R >>\nendobj',
    '2 0 obj\n<< /Type /Pages /Kids [3 0 R] /Count 1 >>\nendobj',
    '3 0 obj\n<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595.28 841.89] /Resources << /Font << /F1 4 0 R /F2 5 0 R >> >> /Contents 6 0 R >>\nendobj',
    '4 0 obj\n<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica /Encoding /WinAnsiEncoding >>\nendobj',
    '5 0 obj\n<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold /Encoding /WinAnsiEncoding >>\nendobj',
    `6 0 obj\n<< /Length ${streamLength} >>\nstream\n${streamContent}\nendstream\nendobj`,
    `7 0 obj\n<< /Title (${escapePdfText(normalizePdfText(title))}) /Author (ZapDocs LegalTech Platform) /Subject (${escapePdfText(normalizePdfText(subject))}) /CreationDate (D:${createdAt}Z) >>\nendobj`
  ];

  let pdf = '%PDF-1.4\n%\xE2\xE3\xCF\xD3\n';
  const xrefOffsets = [];
  objects.forEach((object) => {
    xrefOffsets.push(encoder.encode(pdf).length);
    pdf += `${object}\n`;
  });

  const startxref = encoder.encode(pdf).length;
  pdf += `xref\n0 ${objects.length + 1}\n`;
  pdf += '0000000000 65535 f \n';
  xrefOffsets.forEach((offset) => {
    pdf += `${String(offset).padStart(10, '0')} 00000 n \n`;
  });
  pdf += `trailer\n<< /Size ${objects.length + 1} /Root 1 0 R /Info 7 0 R >>\n`;
  pdf += `startxref\n${startxref}\n%%EOF\n`;

  return encoder.encode(pdf);
}

/**
 * Downloads PDF bytes through the same Blob URL lifecycle used by agreement PDFs.
 *
 * @param {Uint8Array} pdfBytes Binary PDF data
 * @param {string} filename Download filename
 */
export function downloadPdfBytes(pdfBytes, filename) {
  if (!(pdfBytes instanceof Uint8Array) || pdfBytes.length === 0) {
    throw new Error('Valid PDF bytes are required for download.');
  }
  if (!filename || typeof filename !== 'string') {
    throw new Error('A PDF filename is required for download.');
  }

  const blob = new Blob([pdfBytes], { type: 'application/pdf' });
  const url = URL.createObjectURL(blob);
  const anchor = document.createElement('a');

  anchor.style.display = 'none';
  anchor.href = url;
  anchor.download = filename;
  document.body.appendChild(anchor);
  anchor.click();

  setTimeout(() => {
    document.body.removeChild(anchor);
    URL.revokeObjectURL(url);
  }, 1000);
}

// Helpers to format rental and deposit values safely
function formatRent(val) {
  if (val == null || val === '') return 'Rs. 28,000 / month';
  if (typeof val === 'number') {
    return `Rs. ${val.toLocaleString('en-IN')} / month`;
  }
  const s = String(val).trim();
  if (s.toLowerCase().includes('month')) return s;
  if (s.startsWith('Rs') || s.startsWith('₹')) return `${s} / month`;
  const num = Number(s.replace(/[^0-9.-]+/g, ''));
  if (!isNaN(num) && s.length < 12) {
    return `Rs. ${num.toLocaleString('en-IN')} / month`;
  }
  return `Rs. ${s} / month`;
}

function formatDeposit(val) {
  if (val == null || val === '') return 'Rs. 1,50,000';
  if (typeof val === 'number') {
    return `Rs. ${val.toLocaleString('en-IN')}`;
  }
  const s = String(val).trim();
  if (s.startsWith('Rs') || s.startsWith('₹')) return s;
  const num = Number(s.replace(/[^0-9.-]+/g, ''));
  if (!isNaN(num) && s.length < 12) {
    return `Rs. ${num.toLocaleString('en-IN')}`;
  }
  return `Rs. ${s}`;
}

